#!/usr/bin/env python3
"""Deterministic I420 clip generation for certification cases.

Adapted from the ideas in ``bench/generate_clip.py`` (which this module does
not import or modify): analytic, integer-seeded patterns rather than random
state, so a case can be regenerated byte-for-byte from its parameters.  The
certification team owns this copy so that a published measurement never
depends on files outside ``cert/``.

Content kinds map the usage model's vocabulary onto a small set of synthetic
materials.  Unknown names are mapped deterministically and the mapping is
recorded in the clip manifest.
"""

from __future__ import annotations

import hashlib
import json
import math
import platform
import re
import subprocess
from pathlib import Path

try:
    import numpy as np
except ImportError as exc:  # pragma: no cover - environment has numpy
    raise SystemExit("cert/clipgen.py requires numpy (for deterministic, fast clip generation)") from exc

GENERATOR_VERSION = 2
CONTENT_KINDS = ("synthetic", "motion", "grain", "flat", "edges", "gradient")

# Usage-model vocabulary -> generator material.  Anything not listed is
# hashed to one of CONTENT_KINDS (stable across runs) and flagged in output.
CONTENT_ALIASES = {
    "synthetic": "synthetic", "drifting": "synthetic", "analytic": "synthetic",
    "natural": "synthetic", "photo": "synthetic", "camera": "synthetic",
    "motion": "motion", "fast-motion": "motion", "sport": "motion",
    "action": "motion", "moving": "motion",
    "grain": "grain", "noise": "grain", "noisy": "grain",
    "high-detail": "grain", "detail": "grain", "film": "grain",
    "flat": "flat", "still": "flat", "static": "flat",
    "animation": "flat", "cartoon": "flat", "talking-head": "flat",
    "edges": "edges", "text": "edges", "screen": "edges",
    "screenshare": "edges", "slides": "edges", "ui": "edges",
    "gradient": "gradient", "smooth": "gradient",
}


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def normalize_content(name: str) -> tuple[str, bool]:
    """Return (generator material, was_guessed)."""
    key = (name or "synthetic").strip().lower().replace("_", "-")
    if key in CONTENT_ALIASES:
        return CONTENT_ALIASES[key], False
    if key in CONTENT_KINDS:
        return key, False
    digest = hashlib.sha256(key.encode("utf-8")).digest()
    return CONTENT_KINDS[digest[0] % len(CONTENT_KINDS)], True


def _noise_array(xs, ys, t, seed):
    """Integer-hash noise, identical in spirit to bench's generator."""
    mask = np.uint64(0xFFFFFFFFFFFFFFFF)
    v = (xs * np.uint64(374761393) + ys * np.uint64(668265263)
         + np.uint64(t) * np.uint64(1442695041) + np.uint64(seed)) & mask
    v ^= v >> np.uint64(13)
    v = (v * np.uint64(1274126177)) & mask
    v ^= v >> np.uint64(16)
    return (v & np.uint64(0xFF)).astype(np.float64) - 127.5


def _plane(w, h, t, seed, kind, chroma, plane_index):
    xs = np.arange(w, dtype=np.uint64)[None, :]
    ys = np.arange(h, dtype=np.uint64)[:, None]
    xf = xs.astype(np.float64)
    yf = ys.astype(np.float64)
    # Per-plane seed offset keeps U and V independent, as in the bench clip.
    nf = _noise_array(xs, ys, t, seed + plane_index * 7919)
    tau = 2.0 * math.pi

    if chroma:
        amp = {"flat": 0.04, "edges": 0.05, "gradient": 0.04,
               "grain": 0.55, "motion": 0.10, "synthetic": 0.09}[kind]
        val = (128.0
               + 27.0 * np.sin(xf / w * tau * 2.0 + t * 0.043)
               + 15.0 * np.cos(yf / h * tau * 3.0 - t * 0.031)
               + nf * amp)
        return np.clip(val, 0, 255).astype(np.uint8).tobytes()

    if kind == "grain":
        val = (120.0 + 34.0 * np.sin(xf / w * tau * 2.0 + t * 0.05)
               + 19.0 * np.cos(yf / h * tau * 3.0 - t * 0.04)
               + 26.0 * xf / w + nf * 0.80)
    elif kind == "flat":
        val = (118.0 + 9.0 * np.sin(xf / w * tau + t * 0.02)
               + 6.0 * np.cos(yf / h * tau - t * 0.015) + nf * 0.03)
    elif kind == "edges":
        val = (96.0 + 46.0 * (xf / w > 0.38) + 28.0 * (yf / h > 0.62))
        bx = int((t * 11) % max(1, w - w // 5))
        by = int((t * 7) % max(1, h - h // 4))
        mask = ((xf >= bx) & (xf < bx + w // 5) &
                (yf >= by) & (yf < by + h // 4))
        val = val + 58.0 * mask + nf * 0.02
    elif kind == "gradient":
        val = 24.0 + 182.0 * xf / w + 26.0 * yf / h + nf * 0.02
    elif kind == "motion":
        val = (104.0 + 28.0 * np.sin(xf / w * tau * 2.0 + t * 0.09)
               + 17.0 * np.cos(yf / h * tau * 2.0 - t * 0.06)
               + 22.0 * xf / w + nf * 0.10)
        for direction, phase in ((1.0, 0.0), (-1.0, math.pi / 2.0)):
            cx = w * 0.5 + w * 0.40 * math.sin(t * 0.055 + phase) * direction
            cy = h * 0.5 + h * 0.32 * math.cos(t * 0.047 + phase)
            d2 = (xf - cx) ** 2 + (yf - cy) ** 2
            val += 62.0 * np.exp(-d2 / (2.0 * (h * 0.10) ** 2))
    else:  # "synthetic": same analytic material as the bench clip
        val = (112.0
               + 38.0 * np.sin(xf / w * tau * 3.0 + t * 0.11 + yf / h * tau * 0.6)
               + 24.0 * np.sin(yf / h * tau * 2.0 - t * 0.07)
               + 26.0 * xf / w + 16.0 * yf / h + nf * 0.12)
        cx = w * 0.5 + w * 0.42 * math.sin(t * 0.045)
        cy = h * 0.5 + h * 0.34 * math.cos(t * 0.061)
        d2 = (xf - cx) ** 2 + (yf - cy) ** 2
        val += 58.0 * np.exp(-d2 / (2.0 * (h * 0.09) ** 2))
        bx = int((t * 9) % max(1, w - 70))
        by = int((t * 5) % max(1, h - 44))
        val[by:by + 44, bx:bx + 70] += 34.0
    return np.clip(val, 0, 255).astype(np.uint8).tobytes()


def _clip_filename(case: dict) -> str:
    safe = re.sub(r"[^A-Za-z0-9_-]+", "_", str(case["content"])).strip("_") or "unknown"
    return (f"clip_{case['width']}x{case['height']}_{case['frames']}f_"
            f"{safe}_s{case['seed']}.yuv")


def _expected_manifest(case: dict, kind: str, filename: str) -> dict:
    return {
        "generator": "cert/clipgen.py",
        "generator_version": GENERATOR_VERSION,
        "backend": "numpy",
        "width": case["width"], "height": case["height"],
        "frames": case["frames"], "fps": case["fps"], "seed": case["seed"],
        "content_requested": case["content"], "content_kind": kind,
        "format": "I420 / YUV420P, 8-bit, planar",
        "file": filename,
    }


def ensure_clip(assets_dir: Path, case: dict) -> dict:
    """Reuse a verified clip or write a new one; return its manifest."""
    width, height = case["width"], case["height"]
    frames = case["frames"]
    if width <= 0 or height <= 0 or width % 2 or height % 2:
        raise ValueError("width and height must be positive even integers")
    if frames <= 0:
        raise ValueError("frames must be positive")

    kind, guessed = normalize_content(case["content"])
    filename = _clip_filename(case)
    path = assets_dir / filename
    mp = path.with_suffix(path.suffix + ".manifest.json")
    expected = _expected_manifest(case, kind, filename)

    if path.is_file() and mp.is_file():
        try:
            m = json.loads(mp.read_text(encoding="utf-8"))
            if (all(m.get(k) == v for k, v in expected.items())
                    and m.get("sha256") == sha256_file(path)
                    and m.get("size_bytes") == path.stat().st_size):
                m["reused"] = True
                m["content_guessed"] = guessed
                return m
        except (ValueError, OSError, KeyError):
            pass  # regenerate below

    assets_dir.mkdir(parents=True, exist_ok=True)
    cw, ch = width // 2, height // 2
    with open(path, "wb") as f:
        for t in range(frames):
            f.write(_plane(width, height, t, case["seed"], kind, False, 0))
            f.write(_plane(cw, ch, t, case["seed"], kind, True, 1))
            f.write(_plane(cw, ch, t, case["seed"], kind, True, 2))

    expected.update({
        "content_guessed": guessed,
        "size_bytes": path.stat().st_size,
        "sha256": sha256_file(path),
        "numpy_version": np.__version__,
        "python_version": platform.python_version(),
        "reused": False,
    })
    mp.write_text(json.dumps(expected, indent=2) + "\n", encoding="utf-8")
    return expected


def _ffmpeg_version(ffmpeg: Path) -> str:
    try:
        p = subprocess.run([str(ffmpeg), "-version"], stdout=subprocess.PIPE,
                           stderr=subprocess.STDOUT, timeout=30)
        return p.stdout.decode("utf-8", "replace").splitlines()[0].strip()
    except (OSError, subprocess.TimeoutExpired, IndexError):
        return "<unknown>"


def ensure_ffmpeg_clip(assets_dir: Path, case: dict, ffmpeg: Path,
                       source_template: str, timeout: float = 600.0) -> dict:
    """Generate a clip from the spec's deterministic ffmpeg lavfi source.

    The source template is from ``spec/usage-model.md`` §1.1; ``WxH`` and
    ``rate=30`` are substituted with the sampled case parameters.  Media is
    cached outside the repository (the spec requires temp-dir media) and
    verified by SHA256 before reuse.
    """
    if not source_template or "WxH" not in source_template:
        raise ValueError("invalid lavfi source template (expected 'WxH' placeholder)")
    width, height, frames = case["width"], case["height"], case["frames"]
    if width <= 0 or height <= 0 or width % 2 or height % 2 or frames <= 0:
        raise ValueError("width/height must be positive even integers, frames positive")
    source = (source_template.replace("WxH", f"{width}x{height}")
              .replace("rate=30", f"rate={case['fps']}"))
    source = re.sub(r"\br=30\b", f"r={case['fps']}", source)
    safe = re.sub(r"[^A-Za-z0-9_-]+", "_", str(case["content"])).strip("_") or "unknown"
    filename = f"lavfi_{safe}_{width}x{height}_{frames}f_s{case['seed']}.yuv"
    path = assets_dir / filename
    mp = path.with_suffix(path.suffix + ".manifest.json")
    expected = {
        "generator": "ffmpeg lavfi (spec/usage-model.md §1.1)",
        "generator_version": GENERATOR_VERSION,
        "width": width, "height": height, "frames": frames,
        "fps": case["fps"], "seed": case["seed"],
        "content_requested": case["content"], "content_kind": case["content"],
        "source_template": source_template, "resolved_source": source,
        "format": "I420 / YUV420P, 8-bit, planar",
        "file": filename,
    }
    if path.is_file() and mp.is_file():
        try:
            m = json.loads(mp.read_text(encoding="utf-8"))
            if (all(m.get(k) == v for k, v in expected.items())
                    and m.get("sha256") == sha256_file(path)
                    and m.get("size_bytes") == path.stat().st_size):
                m["reused"] = True
                m["content_guessed"] = False
                return m
        except (ValueError, OSError, KeyError):
            pass
    assets_dir.mkdir(parents=True, exist_ok=True)
    cmd = [str(ffmpeg), "-hide_banner", "-loglevel", "error", "-y",
           "-f", "lavfi", "-i", source, "-frames:v", str(frames),
           "-pix_fmt", "yuv420p", "-f", "rawvideo", str(path)]
    try:
        p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                           timeout=timeout)
    except subprocess.TimeoutExpired as exc:
        raise RuntimeError(f"lavfi clip generation timed out after {timeout:g}s") from exc
    if p.returncode != 0 or not path.is_file() or path.stat().st_size == 0:
        raise RuntimeError("lavfi clip generation failed: "
                           + p.stderr.decode("utf-8", "replace").strip()[-500:])
    expected.update({
        "reused": False, "content_guessed": False,
        "size_bytes": path.stat().st_size, "sha256": sha256_file(path),
        "ffmpeg_version": _ffmpeg_version(ffmpeg),
    })
    mp.write_text(json.dumps(expected, indent=2) + "\n", encoding="utf-8")
    return expected


def verify_clip(assets_dir: Path, case: dict) -> bool:
    """True when a cached clip matches its manifest exactly."""
    filename = _clip_filename(case)
    path = assets_dir / filename
    mp = path.with_suffix(path.suffix + ".manifest.json")
    if not path.is_file() or not mp.is_file():
        return False
    try:
        m = json.loads(mp.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        return False
    kind, _ = normalize_content(case["content"])
    expected = _expected_manifest(case, kind, filename)
    return (all(m.get(k) == v for k, v in expected.items())
            and m.get("sha256") == sha256_file(path))
